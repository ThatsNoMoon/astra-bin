import type { KVNamespace } from '@cloudflare/workers-types';

const KEY_CHARSET = 'abcdefghkmprstuwxyz1234567890';
function genKey(length: number): string {
	let key = '';
	for (let i = 0; i < length; i += 1) {
		const charIdx = Math.floor(Math.random() * KEY_CHARSET.length);
		key += KEY_CHARSET[charIdx];
	}
	return key;
}
export function genUniqueKey(length: number, kv: KVNamespace): string {
	let key;
	let found;
	do {
		key = genKey(length);
		found = kv.get(key);
	} while (found == null);

	return key;
}

